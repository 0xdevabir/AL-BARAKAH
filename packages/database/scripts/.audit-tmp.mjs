import pg from 'pg';
import { readFileSync } from 'node:fs';
const c = new pg.Client({ connectionString: process.env.DATABASE_URL });
await c.connect();
const compact = (s) => String(s ?? '').toLowerCase().replace(/[^a-z0-9]+/g, '');
const F = [['eye', /eye|ophthalm/], ['nasal', /nasal/], ['inh', /inhal|respirator|nebul|rotacap/], ['inj', /inject|infusion|\biv\b|\bim\b|vial|ampoule/], ['sup', /supposit|pessary/], ['tab', /tablet|\btab\b|caplet/], ['cap', /capsule|\bcap\b/], ['drop', /drop/], ['liq', /syrup|suspension|solution|elixir|liquid|emulsion/], ['cream', /cream/], ['oint', /ointment/], ['gel', /gel\b/], ['lot', /lotion/], ['pow', /powder|sachet|granule/]];
const fam = (f) => (F.find(([, r]) => r.test(String(f).toLowerCase())) ?? [compact(f)])[0];
const st = (s) => compact(s).replace(/gms?(?![a-z])/g, 'g');
const key = (p) => `${compact(p.name)}|${st(p.strength)}|${fam(p.form)}`;
const all = (await c.query(`SELECT name, strength, form, manufacturer, "createdAt", "isActive", "pricePoisha" FROM "Medicine"`)).rows;
const t0 = new Date(Date.now() - 0);
const cut = new Date('2026-11-02T02:28:00Z');
const older = all.filter((r) => r.createdAt < cut), newer = all.filter((r) => r.createdAt >= cut);
const oldKeys = new Map(older.map((r) => [key(r), r]));
const clones = newer.filter((r) => oldKeys.has(key(r)));
console.log({ older: older.length, newer: newer.length, inactiveNewer: newer.filter((r) => !r.isActive).length, noPriceNewer: newer.filter((r) => !r.pricePoisha).length, newRowsMatchingOld: clones.length });
console.log(clones.slice(0, 15).map((r) => `${r.name} ${r.strength} ${r.form} | ${r.manufacturer} <> ${oldKeys.get(key(r)).manufacturer} / ${oldKeys.get(key(r)).form}`).join('\n'));
const rows = readFileSync('packages/database/data/dims-brands.jsonl', 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
const allKeys = new Set(all.map(key));
const miss = rows.filter((r) => !allKeys.has(key(r)));
